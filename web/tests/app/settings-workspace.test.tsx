import { fireEvent, render, screen, within } from "@testing-library/react";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { SettingsWorkspace } from "../../src/features/settings/SettingsWorkspace";

const scope = { id: "wechat", label: "微信助手", model: "model-a", reasoningEffort: null, revision: "model-v1", editable: true, effect: "下一轮生效", provider: "current-provider" };
const snapshot = { scopes: [scope], chats: [{ chatId: "a", label: "会话 A" }, { chatId: "b", label: "会话 B" }], diagnostics: [{ id: "gateway", label: "Gateway 版本", value: "1.0.0", status: "ok" }] };
const resource = { id: "gateway.preference", kind: "memory", title: "Preference.md", scope: "会话 A", path: "Preference.md", revision: "r1", version: "1.0.0", editable: true, effect: "下一轮读取", content: "简短回复", language: "markdown" };
const document = { ...resource, id: "gateway.prompt", kind: "prompt", title: "微信助手 SP", path: "prompts/leader.md" };
const catalog = { scope: "wechat", models: [{ id: "model-a", label: "模型 A", reasoningEfforts: ["low", "high"] }, { id: "model-b", label: "模型 B", reasoningEfforts: ["medium"] }], fetchedAt: "2026-10-23T08:00:00Z", source: "实际环境", version: "codex 0.163.0", stale: false };
const response = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status });
let calls: { url: string; body: Record<string, unknown> | null; init?: RequestInit }[];
beforeEach(() => {
  calls = [];
  vi.stubGlobal("fetch", vi.fn(async (url: string, init?: RequestInit) => {
    const body = init?.body ? JSON.parse(String(init.body)) : null;
    calls.push({ url, body, init });
    if (url === "/v1/settings") return response(snapshot);
    if (url.startsWith("/v1/settings/models?")) return response(catalog);
    if (url === "/v1/settings/models/refresh") return response(catalog);
    if (url === "/v1/settings/models") return response({ ...scope, ...body, id: body.scope, revision: "model-v2" });
    if (url === "/v1/settings/resources?chatId=a") return response({ resources: [resource] });
    if (url === "/v1/settings/resources?chatId=b") return response({ resources: [{ ...resource, scope: "会话 B" }] });
    if (url === "/v1/settings/resources") return response({ resources: [document] });
    if (url === "/v1/settings/resources/gateway.preference?chatId=a") return response(resource);
    if (url === "/v1/settings/resources/gateway.preference?chatId=b") return response({ ...resource, scope: "会话 B", content: "会话 B 偏好" });
    if (url === "/v1/settings/resources/gateway.preference") return response({ ...resource, ...body, revision: "r2" });
    if (url === "/v1/settings/resources/gateway.prompt") return response(body ? { ...document, ...body, revision: "r2" } : document);
    return response({}, 404);
  }));
});
afterEach(() => vi.unstubAllGlobals());
const renderSettings = () => render(<SettingsWorkspace theme="light" onThemeChange={vi.fn()} themeError={null} onAuthFailure={vi.fn()} onBack={vi.fn()} />);
it("保持三组设置，动态目录选择只允许该模型推理强度并以版本保存", async () => {
  renderSettings();
  const nav = screen.getByRole("navigation", { name: "设置分类" });
  expect(within(nav).getAllByRole("button").map(item => item.textContent)).toEqual(["模型", "记忆与偏好", "外观与诊断"]);
  const models = await screen.findByRole("combobox", { name: "微信助手模型" });
  fireEvent.click(models);
  fireEvent.click(screen.getByRole("option", { name: "模型 B" }));
  fireEvent.click(screen.getByRole("combobox", { name: "微信助手推理强度" }));
  expect(screen.queryByRole("option", { name: "high" })).toBeNull();
  fireEvent.click(screen.getByRole("option", { name: "medium" }));
  fireEvent.click(screen.getByRole("button", { name: "保存" }));
  await screen.findByText("已保存，下一轮生效");
  const saved = calls.find(item => item.url === "/v1/settings/models");
  expect(saved?.body).toEqual({ scope: "wechat", model: "model-b", reasoningEffort: "medium", expectedRevision: "model-v1" });
  expect(saved?.init?.headers).toMatchObject({ "X-Super-Leader-Intent": "settings-update" });
}, 15000);
it("按微信会话隔离记忆，草稿切换需确认，成功保存携带chat和revision", async () => {
  renderSettings();
  await screen.findByRole("combobox", { name: "微信助手模型" });
  fireEvent.click(screen.getByRole("button", { name: "记忆与偏好" }));
  fireEvent.click(await screen.findByRole("button", { name: /Preference.md/ }));
  const editor = await screen.findByLabelText("文件内容");
  fireEvent.change(editor, { target: { value: "只通知结果" } });
  fireEvent.change(screen.getByLabelText("微信会话"), { target: { value: "b" } });
  expect(screen.getByRole("dialog", { name: "放弃未保存的修改？" })).toBeInTheDocument();
  fireEvent.click(screen.getByRole("button", { name: "保留" }));
  expect(editor).toHaveValue("只通知结果");
  fireEvent.click(screen.getByRole("button", { name: "保存" }));
  await screen.findByText("已保存");
  expect(calls.find(item => item.url === "/v1/settings/resources/gateway.preference")?.body).toEqual({ chatId: "a", content: "只通知结果", expectedRevision: "r1" });
  fireEvent.change(screen.getByLabelText("微信会话"), { target: { value: "b" } });
  fireEvent.click(await screen.findByRole("button", { name: /Preference.md/ }));
  expect(await screen.findByLabelText("文件内容")).toHaveValue("会话 B 偏好");
}, 15000);
it("高级资源使用真实文档和保存回执，诊断展示版本及实际请求耗时", async () => {
  renderSettings();
  await screen.findByRole("combobox", { name: "微信助手模型" });
  const advanced = screen.getByText("高级资源").closest("details")!;
  advanced.open = true;
  fireEvent(advanced, new Event("toggle"));
  fireEvent.click(await screen.findByRole("button", { name: /微信助手 SP/ }));
  const promptEditor = await screen.findByLabelText("文件内容");
  fireEvent.change(promptEditor, { target: { value: "新的系统提示" } });
  fireEvent.click(within(promptEditor.closest(".settings-resource-editor") as HTMLElement).getByRole("button", { name: "保存" }));
  await screen.findByText("已保存");
  expect(calls.find(item => item.url === "/v1/settings/resources/gateway.prompt" && item.body)?.body).toEqual({ content: "新的系统提示", expectedRevision: "r1" });
  fireEvent.click(screen.getByRole("button", { name: "外观与诊断" }));
  expect(screen.getByText("Gateway 版本")).toBeVisible();
  expect(screen.getByText(/\d+ ms/)).toBeVisible();
}, 15000);
